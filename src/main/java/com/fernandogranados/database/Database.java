package com.fernandogranados.database;

import com.fernandogranados.database.DatabaseFactory.DatabaseType;
import com.fernandogranados.exception.ErrorWithCode;
import com.fernandogranados.model.Alumno;
import com.fernandogranados.model.Calificaciones;
import com.fernandogranados.model.Materia;
import com.fernandogranados.repository.CrudRepository;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Optional;
import java.util.stream.Collectors;

public final class Database implements AutoCloseable {
  private final Connection connection;
  private final DatabaseType type;

  Database(DatabaseType type, Connection connection) {
    this.type = type;
    this.connection = connection;
    String id = type == DatabaseType.POSTGRESQL
        ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER AUTO_INCREMENT PRIMARY KEY";
    try (Statement statement = connection.createStatement()) {
      statement.executeUpdate("""
          CREATE TABLE IF NOT EXISTS alumnos (
            id %s,
            nombre VARCHAR(150) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
            matricula VARCHAR(50) NOT NULL UNIQUE CHECK (CHAR_LENGTH(TRIM(matricula)) > 0),
            especialidad VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(especialidad)) > 0),
            fecha_ingreso VARCHAR(50) NOT NULL CHECK (CHAR_LENGTH(TRIM(fecha_ingreso)) > 0)
          )
          """.formatted(id));
      statement.executeUpdate("""
          CREATE TABLE IF NOT EXISTS materias (
            id %s,
            nombre VARCHAR(150) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
            creditos SMALLINT NOT NULL CHECK (creditos BETWEEN 0 AND 127),
            especialidad VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(especialidad)) > 0)
          )
          """.formatted(id));
      statement.executeUpdate("""
          CREATE TABLE IF NOT EXISTS calificaciones (
            id %s,
            id_alumno INTEGER NOT NULL,
            id_materia INTEGER NOT NULL,
            calificacion SMALLINT NOT NULL CHECK (calificacion BETWEEN 0 AND 100),
            periodo SMALLINT NOT NULL CHECK (periodo > 0),
            UNIQUE (id_alumno, id_materia, periodo),
            FOREIGN KEY (id_alumno) REFERENCES alumnos(id),
            FOREIGN KEY (id_materia) REFERENCES materias(id)
          )
          """.formatted(id));
    } catch (SQLException error) {
      try {
        connection.close();
      } catch (SQLException closeError) {
        error.addSuppressed(closeError);
      }
      throw sqlError("crear tablas", error);
    }
  }

  public DatabaseType type() {
    return type;
  }

  public CrudRepository<Alumno> alumnos() {
    return new JdbcRepository<Alumno>("alumnos", "nombre", "matricula", "especialidad", "fecha_ingreso") {
      @Override
      Alumno map(ResultSet row) throws SQLException {
        return new Alumno(row.getInt("id"), row.getString("nombre"), row.getString("matricula"),
            row.getString("especialidad"), row.getString("fecha_ingreso"));
      }

      @Override
      Object[] values(Alumno entity) {
        return new Object[] {entity.getNombre(), entity.getMatricula(), entity.getEspecialidad(), entity.getFechaIngreso()};
      }
    };
  }

  public CrudRepository<Materia> materias() {
    return new JdbcRepository<Materia>("materias", "nombre", "creditos", "especialidad") {
      @Override
      Materia map(ResultSet row) throws SQLException {
        return new Materia(row.getInt("id"), row.getString("nombre"), row.getByte("creditos"), row.getString("especialidad"));
      }

      @Override
      Object[] values(Materia entity) {
        return new Object[] {entity.getNombre(), entity.getCreditos(), entity.getEspecialidad()};
      }
    };
  }

  public CrudRepository<Calificaciones> calificaciones() {
    return new JdbcRepository<Calificaciones>("calificaciones", "id_alumno", "id_materia", "calificacion", "periodo") {
      @Override
      Calificaciones map(ResultSet row) throws SQLException {
        return new Calificaciones(row.getInt("id"), row.getInt("id_alumno"), row.getInt("id_materia"),
            row.getShort("calificacion"), row.getShort("periodo"));
      }

      @Override
      Object[] values(Calificaciones entity) {
        return new Object[] {entity.getIdAlumno(), entity.getIdMateria(), entity.getCalificacion(), entity.getPeriodo()};
      }
    };
  }

  @Override
  public void close() {
    try {
      connection.close();
    } catch (SQLException error) {
      throw sqlError("cerrar conexión", error);
    }
  }

  private ErrorWithCode sqlError(String operation, SQLException error) {
    return new ErrorWithCode("DATABASE",
        "[" + type + "] No se pudo " + operation + ". SQLState: " + error.getSQLState(), error);
  }

  private abstract class JdbcRepository<T> implements CrudRepository<T> {
    private final String table;
    private final String select;
    private final String insert;
    private final String update;

    JdbcRepository(String table, String... columns) {
      this.table = table;
      this.select = "SELECT id, " + String.join(", ", columns) + " FROM " + table;
      this.insert = "INSERT INTO " + table + " (" + String.join(", ", columns) + ") VALUES ("
          + String.join(", ", java.util.Collections.nCopies(columns.length, "?")) + ")";
      this.update = "UPDATE " + table + " SET "
          + Arrays.stream(columns).map(column -> column + " = ?").collect(Collectors.joining(", ")) + " WHERE id = ?";
    }

    abstract T map(ResultSet row) throws SQLException;
    abstract Object[] values(T entity);

    @Override
    public int create(T entity) {
      requireEntity(entity);
      try (PreparedStatement statement = connection.prepareStatement(insert, new String[] {"id"})) {
        bind(statement, values(entity));
        statement.executeUpdate();
        try (ResultSet keys = statement.getGeneratedKeys()) {
          if (!keys.next()) throw new ErrorWithCode("DATABASE", "[" + type + "] No se recibió el ID generado.");
          return keys.getInt(1);
        }
      } catch (SQLException error) {
        throw sqlError("crear en " + table, error);
      }
    }

    @Override
    public Optional<T> findById(int id) {
      requireId(id);
      try (PreparedStatement statement = connection.prepareStatement(select + " WHERE id = ?")) {
        statement.setInt(1, id);
        try (ResultSet row = statement.executeQuery()) {
          return row.next() ? Optional.of(map(row)) : Optional.empty();
        }
      } catch (SQLException error) {
        throw sqlError("leer " + table, error);
      }
    }

    @Override
    public List<T> findAll() {
      try (PreparedStatement statement = connection.prepareStatement(select + " ORDER BY id");
           ResultSet rows = statement.executeQuery()) {
        List<T> result = new ArrayList<>();
        while (rows.next()) result.add(map(rows));
        return result;
      } catch (SQLException error) {
        throw sqlError("listar " + table, error);
      }
    }

    @Override
    public boolean update(int id, T entity) {
      requireId(id);
      requireEntity(entity);
      Object[] fields = values(entity);
      try (PreparedStatement statement = connection.prepareStatement(update)) {
        bind(statement, fields);
        statement.setInt(fields.length + 1, id);
        return statement.executeUpdate() > 0;
      } catch (SQLException error) {
        throw sqlError("actualizar " + table, error);
      }
    }

    @Override
    public boolean delete(int id) {
      requireId(id);
      try (PreparedStatement statement = connection.prepareStatement("DELETE FROM " + table + " WHERE id = ?")) {
        statement.setInt(1, id);
        return statement.executeUpdate() > 0;
      } catch (SQLException error) {
        throw sqlError("eliminar de " + table, error);
      }
    }

    private void bind(PreparedStatement statement, Object[] fields) throws SQLException {
      for (int index = 0; index < fields.length; index++) statement.setObject(index + 1, fields[index]);
    }

    private void requireId(int id) {
      if (id <= 0) throw new ErrorWithCode("INVALID_DATA", "El ID debe ser positivo.");
    }

    private void requireEntity(T entity) {
      if (entity == null) throw new ErrorWithCode("INVALID_DATA", "La entidad es obligatoria.");
    }
  }
}
